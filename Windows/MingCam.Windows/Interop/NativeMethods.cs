    public static RECT GetAccurateWindowRect(IntPtr hWnd)
    {
        if (DwmGetWindowAttribute(hWnd, DWMWA_EXTENDED_FRAME_BOUNDS, out RECT rect, Marshal.SizeOf<RECT>()) == 0
            && rect.Width > 0 && rect.Height > 0)
        {
            return rect;
        }
        GetWindowRect(hWnd, out rect);
        return rect;
    }

    public static List<MonitorTargetItem> GetMonitors()
    {
        var list = new List<MonitorTargetItem>();
        int index = 1;
        EnumDisplayMonitors(IntPtr.Zero, IntPtr.Zero, (IntPtr hMon, IntPtr _, ref RECT _, IntPtr _) =>
        {
            var info = new MONITORINFOEX { cbSize = Marshal.SizeOf<MONITORINFOEX>() };
            if (GetMonitorInfo(hMon, ref info))
            {
                bool isPrimary = (info.dwFlags & 1) != 0;
                list.Add(new MonitorTargetItem
                {
                    Handle = hMon,
                    Name = $"顯示器 {index++}",
                    Left = info.rcMonitor.Left,
                    Top = info.rcMonitor.Top,
                    Width = info.rcMonitor.Width,
                    Height = info.rcMonitor.Height,
                    IsPrimary = isPrimary
                });
            }
            return true;
        }, IntPtr.Zero);
        return list;
    }

    public static List<WindowTargetItem> GetCapturableWindows(IntPtr ownWindowHandle)
    {
        var result = new List<WindowTargetItem>();
        uint ownPid = (uint)Environment.ProcessId;

        EnumWindows((hWnd, _) =>
        {
            if (hWnd == ownWindowHandle || !IsWindowVisible(hWnd) || IsIconic(hWnd))
                return true;

            int len = GetWindowTextLength(hWnd);
            if (len <= 0)
                return true;

            if (DwmGetWindowAttribute(hWnd, DWMWA_CLOAKED, out int cloaked, sizeof(int)) == 0 && cloaked != 0)
                return true;

            var rect = GetAccurateWindowRect(hWnd);
            if (rect.Width < 80 || rect.Height < 60)
                return true;

            var sb = new StringBuilder(len + 1);
            GetWindowText(hWnd, sb, sb.Capacity);
            string title = sb.ToString().Trim();
            if (string.IsNullOrEmpty(title))
                return true;

            GetWindowThreadProcessId(hWnd, out uint pid);
            if (pid == ownPid)
                return true;

            string procName = string.Empty;
            try
            {
                using var proc = Process.GetProcessById((int)pid);
                procName = proc.ProcessName;
            }
            catch
            {
                // Ignore protected system processes
            }

            result.Add(new WindowTargetItem
            {
                Handle = hWnd,
                Title = title,
                ProcessName = procName
            });
            return true;
        }, IntPtr.Zero);

        return result;
    }
